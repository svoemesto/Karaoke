// BR-300 / BR-315 / BR-321 (аудит #336, пакет PKG-S3-27, OpenProject #399):
// «latest-request guard» — применять ответ ТОЛЬКО последнего запроса.
//
// ЧТО БЫЛО. Три независимых места гоняли один и тот же ресурс без секвенции:
//   - `useSongSubscription.loadPrice()` — цена предыдущей песни применялась к текущей;
//   - `useSiteSubscription.loadPrice()` — цена первого тарифа оставалась при выбранном втором;
//   - `songs/loadMoreSearchResults` — страница 2 СТАРОГО запроса дописывалась к результатам
//     НОВОГО поиска, а `searchPagination` перезаписывался старыми page/totalCount.
//
// ЧТО СТАЛО. Единый счётчик поколений на «выдачу»: `begin()` возвращает номер поколения,
// `isCurrent(id)` проверяет, что ответ относится к последнему запросу. Старый ответ
// отбрасывается целиком (не трогает ни данные, ни флаги ошибки/загрузки).
//
// Модуль без зависимостей — тест запускается node --test без node_modules.

/**
 * Счётчик поколений запросов.
 *
 * @returns {{begin: () => number, isCurrent: (id: number) => boolean, invalidate: () => number, current: () => number}}
 */
export function createRequestGuard() {
  let seq = 0
  return {
    /** Открыть новое поколение запросов. Возвращает его номер. */
    begin() {
      seq += 1
      return seq
    },
    /** Ответ относится к последнему запросу? */
    isCurrent(id) {
      return id === seq
    },
    /** Сделать все текущие ответы «устаревшими» (без открытия нового поколения). */
    invalidate() {
      seq += 1
      return seq
    },
    /** Номер текущего поколения. */
    current() {
      return seq
    },
  }
}
