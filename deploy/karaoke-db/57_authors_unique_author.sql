-- BR-628 (аудит #336, заключительные замечания владельца от 2026-10-26):
-- уникальность имени автора в tbl_authors.
--
-- Зачем: без ограничения можно завести двух авторов с одинаковым именем. Дальше
-- это расходится по каталогу (авторы-тайлы, поиск по имени, счётчики песен у
-- автора считаются по id), и в интерфейсе появляются «двойники» — слить их
-- потом можно только вручную.
--
-- Проверено перед подготовкой миграции (2026-10-26):
--   LOCAL: 132 автора, 0 групп-дубликатов;
--   PROD:  132 автора, 0 групп-дубликатов.
-- Тем самым создание индекса ничего не ломает и не требует предварительной
-- чистки. Если на момент применения дубликаты появились — CREATE UNIQUE INDEX
-- упадёт с ошибкой (это намеренно: лучше явная ошибка, чем молчаливый дубль).
--
-- Проверка перед применением (должна вернуть 0):
--   SELECT count(*) FROM (
--       SELECT author FROM tbl_authors
--       WHERE author IS NOT NULL
--       GROUP BY author HAVING count(*) > 1
--   ) d;
--
-- Особенности:
--   * `author` — nullable. В PostgreSQL UNIQUE не считает NULL за конфликт,
--     поэтому несколько строк с NULL допустимы (как и сейчас).
--   * Сравнение регистрозависимое: "Иванов" и "иванов" — разные авторы.
--     Это соответствует текущей семантике поиска по имени.
--   * Индекс не блокирует запись надолго: в таблице 132 строки.
--
-- Применять вручную на КАЖДОЙ БД отдельно (Решение 4 в
-- knowledge/system/infra/sql-migrations.md). Идемпотентно: повторный запуск
-- ничего не ломает.
--
-- Откат: DROP INDEX IF EXISTS public.idx_tbl_authors_author_unique;

CREATE UNIQUE INDEX IF NOT EXISTS idx_tbl_authors_author_unique
    ON public.tbl_authors (author);
