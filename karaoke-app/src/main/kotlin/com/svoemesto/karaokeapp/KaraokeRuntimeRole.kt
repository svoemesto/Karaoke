package com.svoemesto.karaokeapp

/**
 * Роль процесса: админское приложение (`karaoke-app` на машине владельца) или веб-приложение
 * прода (`karaoke-web` в контейнере на прод-хосте).
 *
 * Нужна там, где один и тот же общий модельный код выполняется в обоих приложениях, а действие
 * должно происходить только в одном из них.
 *
 * Первый и пока единственный случай — новость «в коллекции» (KARAOKE-338, инцидент 2026-10-30):
 * её создаёт админка в момент перехода флага `newsAvailableAnnounced` false→true, а прод
 * применяет собственную логику при синхронизации. Раньше новость создавалась только на проде,
 * по факту доставки флага, — и терялась, когда флаг не доезжал (поле
 * `player_readiness_flags` намеренно не синхронизируется как «шум готовности файлов»).
 *
 * Значение выставляется в `main` каждого приложения. По умолчанию — [PROD]: консервативно,
 * пока приложение явно не подтвердило, что оно админское (иначе на проде появлялись бы дубли
 * новостей).
 *
 * @see com.svoemesto.karaokeapp.model.Song.saveToDb
 */
object KaraokeRuntimeRole {
    const val ADMIN = "admin"

    const val PROD = "prod"

    @Volatile
    var name: String = PROD

    /** true, если процесс — админское приложение (`karaoke-app`). */
    val isAdmin: Boolean get() = name == ADMIN
}
