package com.svoemesto.karaokeweb.services

/**
 * Признак SKIP-контента — тег `SKIP` в списке тегов песни.
 *
 * SKIP-контент снят по требованию правообладателя (specs/293-skip-author-toggle):
 * он не показывается публично, а видеть его могут только пользователи с правом
 * `canWorkWithSkipped` (автор/владелец контента и админы).
 *
 * Разбор вынесен в один объект: правило «тег SKIP в списке тегов» должно
 * трактоваться одинаково везде (доступ к плееру, публичный каталог, публичные
 * страницы автора) — иначе один из путей может решить, что песня не SKIP.
 */
internal object SkipTag {
    /**
     * Есть ли в [tags] тег `SKIP`.
     *
     * Сравнение регистронезависимое, разделитель — пробел (теги хранятся
     * строкой через пробел). Пустая строка и `null` — не SKIP.
     */
    fun hasSkipTag(tags: String?): Boolean = (tags ?: "").split(" ").any { it.trim().equals("SKIP", ignoreCase = true) }
}
