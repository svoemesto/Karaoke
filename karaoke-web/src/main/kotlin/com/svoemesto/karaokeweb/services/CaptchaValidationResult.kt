package com.svoemesto.karaokeweb.services

/**
 * Исход проверки капчи (спека 564, OpenProject #362, аудит BR-518).
 *
 * До правки проверка возвращала `Boolean`, и два разных отказа — «проверка не настроена» и
 * «внешний сервис недоступен» — неразличимо сводились к «проверка не пройдена», а «пустой
 * серверный ключ» вообще означал «проверка пройдена» (fail-open). Теперь исходов четыре, и
 * каждый из них приводит к отказу регистрации, кроме [PASSED].
 *
 * @property errorCode код отказа, который отдаёт публичный API регистрации
 *   (`{"error": …}`); `null` для [PASSED] — отказа нет.
 */
enum class CaptchaValidationResult(
    val errorCode: String?,
) {
    /** Проверка пройдена: внешний сервис подтвердил токен. */
    PASSED(null),

    /** Проверка не пройдена: токен пуст либо внешний сервис ответил «не ок». */
    FAILED("captcha"),

    /**
     * Проверка не настроена: серверный ключ отсутствует или пуст (незаконная конфигурация).
     *
     * Fail-closed: регистрация отклоняется с отдельным кодом `captcha_not_configured`
     * (решение владельца от 2026-10-24, п. 6).
     */
    NOT_CONFIGURED("captcha_not_configured"),

    /**
     * Проверка невозможна: внешний сервис недоступен (сеть, таймаут, ошибка ответа).
     *
     * Fail-closed: регистрация отклоняется.
     */
    UNAVAILABLE("captcha"),
}
