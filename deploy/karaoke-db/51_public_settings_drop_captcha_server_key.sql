-- Спека 564 (OpenProject #359 + #362, аудит #336: BR-019 + BR-518).
--
-- Серверный (секретный) ключ проверки капчи Yandex SmartCaptcha больше НЕ хранится в
-- публично изменяемой таблице tbl_public_settings: его источник истины — переменная
-- окружения сервиса (CAPTCHA_SERVER_KEY → captcha.server-key в karaoke-web), читаемая при
-- старте. Проверка капчи при незаконной конфигурации — fail-closed (регистрация
-- отклоняется с кодом captcha_not_configured), а не fail-open («пустой ключ = проверка
-- пройдена»), которым анонимный клиент пользовался, обнулив ключ через
-- POST /api/properties/setproperty.
--
-- ПОРЯДОК ВЫПОЛНЕНИЯ (решение владельца от 2026-10-24, п. 4):
--   1. СНАЧАЛА — инвентаризация: снимок всех строк tbl_public_settings (ключ, значение,
--      description, last_update), проверка значения ключа капчи и переключателей, поиск
--      неопознанных ключей. Снимок снимается прямым SQL (psql) на боевой БД — через API
--      значение серверного ключа больше не выдаётся (намеренно).
--   2. ПОТОМ — ротация ключа капчи в панели Yandex SmartCaptcha и выдача нового значения
--      в env (do.env на боевом хосте: CAPTCHA_SERVER_KEY).
--   3. ПОТОМ — эта миграция: строка с ключом удаляется из таблицы.
--   Обнаруженное «отравленное» значение (ключ, отличный от ожидаемого) считается инцидентом
--   безопасности: ключ ротируется обязательно, независимо от остальных действий.
--
-- Идемпотентно: DELETE ... WHERE key = ... не падает, если строки уже нет.

DELETE FROM public.tbl_public_settings WHERE key = 'yandexSmartCaptchaServerKey';
