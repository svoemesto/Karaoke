-- Очистка старого механизма авто-новостей (specs/101-song-news-flag) — заменён двумя независимыми
-- механизмами: флагом «доступна для новости» на самой песне (Song.newsAvailableAnnounced, внутри
-- уже существующего player_readiness_flags — без изменений схемы tbl_songs) и узким скользящим
-- окном плановой проверки «в эфире» (SongReleaseAnnouncementService.checkOnAirWindow), без
-- отдельной таблицы учёта.
--
-- ВАЖНО — порядок операций (см. quickstart.md, Шаг 0-2):
-- 1) Задеплоить новый код (эта фича) на LOCAL и на PROD.
-- 2) Выполнить POST /utils/backfillnewsavailable на LOCAL (target=local) И на PROD
--    (target=remote) — ДО применения этой миграции. Backfill выставляет флаг «доступна» в true для
--    уже готовых сегодня песен БЕЗ создания новости; без этого шага очистка tbl_news ниже
--    спровоцирует лавину новостей «доступна» по всей текущей коллекции при следующей обычной
--    синхронизации любой из этих песен (см. research.md фичи 101, п.3).
-- 3) Только после этого применить эту миграцию — на LOCAL и на PROD отдельно (как и все миграции
--    в этом каталоге — сама на сервер не переносится).
--
-- Очистка tbl_news не создаёт лавину новостей «в эфире» задним числом (в отличие от «доступна»):
-- новый механизм рассматривает только песни, чья дата/время эфира попали в последнее скользящее
-- окно (~10 минут) — старые (уже давно вышедшие в эфир) песни физически никогда не попадают в это
-- окно, поэтому отдельный backfill для них не требуется.

DROP TABLE IF EXISTS public.tbl_song_news_announced;

TRUNCATE TABLE public.tbl_news RESTART IDENTITY;
