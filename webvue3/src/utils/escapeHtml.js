/**
 * Экранирование текста для безопасной вставки в HTML.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ. `escapeHtml` нужен не только подсветке слов в редакторе
 * субтитров, но и всем местам, где пользовательский текст попадает в HTML-буфер:
 * подтверждения админки (`CustomConfirm.vue`, спека #558 / OpenProject #360 /
 * BR-123), тексты новостей и шаблонов публикаций. Реализация была в
 * `highlightWords.js` — оттуда её импортировали только два модуля, но тянуть
 * «модуль про подсветку слов» в восемь компонентов ради одной функции неправильно.
 * Поэтому здесь — каноническая реализация, а `highlightWords.js` реэкспортирует её
 * (обратная совместимость сохранена, поведение не изменилось).
 *
 * ПРАВИЛО ПРОЕКТА. Экранирование выполняется **на входе** в HTML-буфер, а не на
 * выходе: если строка уже собрана как HTML (статичная разметка вроде `<strong>`),
 * экранировать её целиком на отдаче нельзя — сломается вся разметка. Экранировать
 * нужно точечно, в момент, когда значение входит в HTML-буфер.
 * См. `knowledge/domains/integration/components/song-public-dto.md` (прецедент
 * спеки #215) и `knowledge/system/frontend/subs-edit-admin-editor.md`.
 *
 * Экранирование применяется РОВНО ОДИН РАЗ: значение, уже экранированное
 * при сборке HTML, на выходе повторно не экранируется (иначе `&` превратится в
 * `&amp;amp;` на экране).
 */

/**
 * Экранирует текст так, чтобы он не стал разметкой при вставке в innerHTML.
 *
 * @param {string} text - исходный текст
 * @returns {string} текст, в котором & < > " ' экранированы
 */
export function escapeHtml(text) {
  return String(text ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;')
}
