package com.svoemesto.karaokeapp.textfiledictionary

/**
 * Словарь слов, требующих внимания при вычитке текста песни.
 *
 * Общий словарь: подсветка в блоке исходного текста (webvue3, SubsEdit.vue) показывает
 * ровно то, что здесь лежит, и ничего не знает про конкретные правила. Первым набором
 * была неоднозначная «ё», но это не ограничение словаря.
 *
 * Отдельный класс, а не запись в [com.svoemesto.karaokeapp.TEXT_FILE_DICTS] против
 * старого словаря, потому что фасад [TextFileDictionary] ищет обработчик по имени
 * словаря и для незарегистрированного имени МОЛЧА возвращает false — слово не
 * добавлялось, а эндпоинт всё равно рапортовал об успехе.
 *
 * @see AGENTS.md
 */
class AttentionWordsDictionary : TextFileDictionary {
    override fun dictName() = "Слова для внимания"
}
