-- Расширение жизненного цикла статуса готовности песни (id_status) с 4 значений (0-3)
-- до 7 значений (0-6): 0 новая, 1 текст найден, 2 текст проверен (орфография/пунктуация),
-- 3 текст проверен (слова соответствуют песне), 4 маркеры расставлены, 5 маркеры проверены,
-- 6 песня готова. Порог публичной готовности переносится с id_status>=3 на id_status>=6
-- (см. specs/022-song-status-lifecycle/spec.md, contracts/song-status-lifecycle.md).
--
-- Значения 0, 1, 2 численно не меняются (миграция их не трогает). Все песни, у которых
-- id_status уже >= 3 (под старой схемой это означало "готова"), переводятся на 6 — новое
-- терминальное значение "готова" — чтобы не потерять видимость уже опубликованных песен.
--
-- Один раз на LOCAL и на SERVER отдельно.
--
-- BR-535 (аудит #336 / P-71-03, OpenProject #393): условие было `id_status >= 3`,
-- и шапка обещала идемпотентность, которой не было. `>= 3` захватывает не только
-- «мигрированные» строки, но и незавершённые состояния 3/4/5 (TEXT_WORDS_VERIFIED,
-- MARKERS_CREATED, MARKERS_VERIFIED): повторный запуск переводил песню, которая ещё
-- в работе, в 6 = READY, и она уезжала в публичный поиск/плеер (`id_status >= 6`) и
-- в счётчик ready_songs_count.
--
-- Теперь условие — ровно те состояния, которых миграция ещё не касалась:
-- 3, 4 и 5. Строки в 6 (уже мигрированные) и 0/1/2 (миграция их не трогает) повторный
-- запуск не меняет — идемпотентность стала настоящей.

UPDATE public.tbl_songs
SET id_status = 6
WHERE id_status IN (3, 4, 5);
