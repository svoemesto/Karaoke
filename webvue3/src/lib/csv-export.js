// BR-398 (аудит #336, пакет PKG-S3-32, OpenProject #404).
//
// ДЕФЕКТ. CSV-экспорт отчёта о bulk-операции экранировал только кавычки/запятые/
// переводы строк и не нейтрализувал ФОРМУЛЫ. Ячейка, начинающаяся с `=`, `+`, `-`,
// `@`, `TAB` или `CR`, в Excel/LibreOffice исполняется как формула (CSV formula
// injection). Текст ошибки (`err.reason`) формирует бэкенд, поэтому вектор
// пользовательского ввода не доказан — это defense-in-depth.
//
// РЕШЕНИЕ. Значение, начинающееся с опасного символа, получает префикс-апостроф:
// табличный редактор показывает его как ТЕКСТ, а не исполняет. Префикс ставится
// ДО общего quoting (кавычки/запятые), поэтому порядок операций важен.
//
// Числа не трогаем: `count`/`durationMs` не могут быть формулой, а префикс испортил
// бы выгрузку (число превратилось бы в текст).
//
// Модуль вынесен отдельно от модалки — чтобы правило было в одном месте и его можно
// было закрыть регрессионным тестом (BR-398).

/**
 * Символы, с которых табличный редактор начинает интерпретацию ячейки как формулы.
 *
 * @type {string[]}
 */
export const CSV_FORMULA_TRIGGERS = ['=', '+', '-', '@', '\t', '\r']

/**
 * Экранирует значение ячейки CSV: нейтрализует формулу и quoting.
 *
 * @param {*} value — значение ячейки.
 * @returns {string} готовая к записи ячейка.
 */
export function escapeCsvCell(value) {
  if (value === null || value === undefined) return ''
  let s = String(value)
  // BR-398: апостроф-префикс переводит ячейку в текст. Числа исключены осознанно.
  if (typeof value !== 'number' && CSV_FORMULA_TRIGGERS.includes(s.charAt(0))) {
    s = "'" + s
  }
  if (/[",\n]/.test(s)) {
    return '"' + s.replace(/"/g, '""') + '"'
  }
  return s
}

/**
 * Собирает CSV-текст из строк.
 *
 * @param {Array<Array<*>>} rows — строки (ячейки любых типов).
 * @returns {string} CSV-текст с переводами строк `\n`.
 */
export function buildCsv(rows) {
  return (rows || []).map((row) => (row || []).map(escapeCsvCell).join(',')).join('\n')
}
